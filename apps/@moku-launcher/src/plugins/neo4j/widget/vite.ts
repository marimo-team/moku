/**
 * A Vite plugin that generates the notebook cell defining the `CypherGraph` widget.
 *
 * Importing `virtual:moku-neo4j-widget` bundles the {@link https://anywidget.dev | anywidget}
 * front end in `render.ts`, including d3-force and `style.css`, and inlines it
 * into the Python class in `widget.py`. The cell's first line names a version
 * derived from its content, so the Neo4j view can tell when a notebook carries
 * an older copy.
 *
 * @module
 */
import * as NodeCrypto from "node:crypto";
import * as NodeFs from "node:fs/promises";
import * as NodePath from "node:path";
import * as NodeUrl from "node:url";
import * as Vite from "vite-plus";

const id = "virtual:moku-neo4j-widget";
const resolved = `\0${id}`;
const directory = NodeUrl.fileURLToPath(new URL(".", import.meta.url));

// The first line of every generated widget cell, followed by its version.
const marker = "# moku:neo4j-widget ";

/**
 * Provides `virtual:moku-neo4j-widget`, exporting the cell's `source`, its
 * `version`, and the `marker` that starts its first line.
 */
export function neo4jWidget(): Vite.Plugin {
  let cell: Promise<{ source: string; version: string }> | undefined;
  return {
    name: "moku-neo4j-widget",
    resolveId: (source) => (source === id ? resolved : undefined),
    async load(module) {
      if (module !== resolved) return undefined;
      cell ??= generate();
      const { source, version } = await cell;
      return [
        `export const source = ${JSON.stringify(source)};`,
        `export const version = ${JSON.stringify(version)};`,
        `export const marker = ${JSON.stringify(marker)};`,
      ].join("\n");
    },
    handleHotUpdate({ file, server }) {
      if (!file.startsWith(directory) || file.endsWith("vite.ts")) return;
      cell = undefined;
      const module = server.moduleGraph.getModuleById(resolved);
      if (module) server.moduleGraph.invalidateModule(module);
    },
  };
}

async function generate(): Promise<{ source: string; version: string }> {
  const output = await Vite.build({
    configFile: false,
    logLevel: "warn",
    root: directory,
    publicDir: false,
    build: {
      write: false,
      minify: true,
      target: "es2022",
      lib: {
        entry: NodePath.join(directory, "render.ts"),
        formats: ["es"],
        fileName: "widget",
      },
      // Library builds keep whitespace by default; the cell should stay compact.
      rolldownOptions: { output: { minify: true } },
    },
  });
  const outputs = Array.isArray(output) ? output : [output];
  const chunk = outputs
    .flatMap((entry) => ("output" in entry ? entry.output : []))
    .find((entry) => entry.type === "chunk");
  if (!chunk || chunk.type !== "chunk")
    throw new Error("Bundling the Neo4j widget produced no code.");
  const python = await NodeFs.readFile(NodePath.join(directory, "widget.py"), "utf8");
  // JSON string literals are valid Python string literals.
  const body = python
    .replace("__MOKU_ESM__", () => JSON.stringify(chunk.code.trim()))
    .trim();
  const version = NodeCrypto.createHash("sha256")
    .update(body)
    .digest("hex")
    .slice(0, 12);
  const source = [
    `${marker}${version}`,
    "# Generated by moku's Neo4j view, which can update it; edits here are replaced.",
    body,
  ].join("\n");
  return { source, version };
}
